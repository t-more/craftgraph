#!/usr/bin/env python3
"""Builds Data/Recipes.lua from Blizzard's data tables (DB2 CSV exports).

Usage: gen_data.py <dir with CSVs> <output Recipes.lua> <build>
CSVs needed (from https://wago.tools/db2/<Table>/csv?build=<build>):
  SkillLine SkillLineAbility SpellReagents SpellEffect SpellName
  SpellCooldowns ItemSparse Item ItemEffect ItemXItemEffect
"""
import csv, sys, os, collections

src, out, build = sys.argv[1], sys.argv[2], sys.argv[3]

def load(name):
    with open(os.path.join(src, name + '.csv'), newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))

def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'

skill_lines = {int(r['ID']): r for r in load('SkillLine')}
def root_skill(sid):
    seen = set()
    while sid in skill_lines and int(skill_lines[sid]['ParentSkillLineID'] or 0) and sid not in seen:
        seen.add(sid)
        sid = int(skill_lines[sid]['ParentSkillLineID'])
    return sid

spell_skill = {}
for r in load('SkillLineAbility'):
    spell = int(r['Spell'])
    sid = root_skill(int(r['SkillLine']))
    rank = int(r['MinSkillLineRank'] or 0)
    grey = int(r['TrivialSkillLineRankHigh'] or 0)
    yellow = int(r['TrivialSkillLineRankLow'] or 0)
    cur = spell_skill.get(spell)
    if cur is None or (grey and not cur[2]):
        spell_skill[spell] = (sid, rank, grey, yellow)

products = {}
for r in load('SpellEffect'):
    if r['Effect'] != '24' or r['DifficultyID'] != '0':
        continue
    item = int(r['EffectItemType'] or 0)
    if not item:
        continue
    spell = int(r['SpellID'])
    qty = float(r['EffectBasePointsF'] or 1)
    if qty < 1:
        qty = 1
    if spell not in products:
        products[spell] = (item, qty)

names = {int(r['ID']): r['Name_lang'] for r in load('SpellName')}

cooldowns = {}
for r in load('SpellCooldowns'):
    if r['DifficultyID'] != '0':
        continue
    cd = max(int(r['CategoryRecoveryTime'] or 0), int(r['RecoveryTime'] or 0)) // 1000
    if cd >= 3600:
        cooldowns[int(r['SpellID'])] = cd

recipes = {}
used_items = set()
for r in load('SpellReagents'):
    spell = int(r['SpellID'])
    if spell not in products or spell not in spell_skill:
        continue
    reagents = []
    for i in range(8):
        item, count = int(r['Reagent_%d' % i] or 0), int(r['ReagentCount_%d' % i] or 0)
        if item > 0 and count > 0:
            reagents.append((item, count))
    if not reagents:
        continue
    item, qty = products[spell]
    if any(ri == item for ri, _ in reagents):
        continue
    recipes[spell] = (spell_skill[spell], item, qty, reagents)
    used_items.add(item)
    used_items.update(ri for ri, _ in reagents)

# Which item teaches which recipe (a pattern, plans, a formula ...): an item
# effect that either is the recipe's spell, learned on use, or casts a spell
# whose effect is to teach it. Recipes without one are taught by trainers.
learn_spell = {int(r['SpellID']): int(r['EffectTriggerSpell'] or 0)
               for r in load('SpellEffect') if r['Effect'] == '36'}
item_effects = {int(r['ID']): r for r in load('ItemEffect')}
sparse_names = {int(r['ID']): r['Display_lang'] for r in load('ItemSparse')}
teaches = {}
for r in load('ItemXItemEffect'):
    effect = item_effects.get(int(r['ItemEffectID']))
    if not effect:
        continue
    spell, item = int(effect['SpellID']), int(r['ItemID'])
    taught = spell if spell in recipes else learn_spell.get(spell)
    if taught in recipes and sparse_names.get(item):
        if taught not in teaches or item < teaches[taught]:
            teaches[taught] = item
used_items.update(teaches.values())

icons = {int(r['ID']): int(r['IconFileDataID'] or 0) for r in load('Item')}
items = {}
for r in load('ItemSparse'):
    iid = int(r['ID'])
    if iid in used_items:
        items[iid] = (r['Display_lang'], int(r['OverallQualityID'] or 1),
                      int(r['SellPrice'] or 0),
                      -(-int(r['BuyPrice'] or 0) // max(1, int(r['VendorStackCount'] or 1))),
                      icons.get(iid, 0), int(r['Stackable'] or 1),
                      int(r['Bonding'] or 0))

# Drop recipes whose product or reagents are not real items in this build.
recipes = {s: v for s, v in recipes.items()
           if v[1] in items and all(ri in items for ri, _ in v[3])}
teaches = {s: i for s, i in teaches.items() if s in recipes and i in items}

with open(out, 'w', encoding='utf-8') as f:
    f.write('-- Generated by tools/gen_data.py from game data tables, build %s. Do not edit.\n' % build)
    f.write('local _, ns = ...\nns.Data = { build = %s }\n' % lua_str(build))
    f.write('ns.Data.skills = {\n')
    for sid in sorted({v[0][0] for v in recipes.values()}):
        f.write('[%d]=%s,\n' % (sid, lua_str(skill_lines[sid]['DisplayName_lang'] if sid in skill_lines else 'Skill %d' % sid)))
    f.write('}\n')
    f.write('-- [spellID] = { skillLine, minSkill, product itemID, yield, cooldown seconds or 0, name, {item, count, ...},\n')
    f.write('--              skill where it turns yellow, skill where it turns grey }\n')
    f.write('ns.Data.recipes = {\n')
    for spell in sorted(recipes):
        (sid, rank, grey, yellow), item, qty, reagents = recipes[spell]
        q = ('%g' % qty)
        flat = ','.join('%d,%d' % rc for rc in reagents)
        f.write('[%d]={%d,%d,%d,%s,%d,%s,{%s},%d,%d},\n' % (
            spell, sid, rank, item, q, cooldowns.get(spell, 0), lua_str(names.get(spell, '')), flat, yellow, grey))
    f.write('}\n')
    f.write('-- [itemID] = { name, quality, vendor sell, vendor buy, icon, stack size, bonding }\n')
    f.write('ns.Data.items = {\n')
    for iid in sorted(items):
        n, q, sell, buy, icon, stack, bond = items[iid]
        f.write('[%d]={%s,%d,%d,%d,%d,%d,%d},\n' % (iid, lua_str(n), q, sell, buy, icon, stack, bond))
    f.write('}\n')

    f.write('-- [recipe spellID] = the item that teaches it; recipes not listed are taught by trainers\n')
    f.write('ns.Data.teaches = {\n')
    for spell in sorted(teaches):
        f.write('[%d]=%d,\n' % (spell, teaches[spell]))
    f.write('}\n')

print('recipes taught by an item:', len(teaches))
by_skill = collections.Counter(skill_lines[v[0][0]]['DisplayName_lang'] if v[0][0] in skill_lines else str(v[0][0]) for v in recipes.values())
print('recipes:', len(recipes), 'items:', len(items))
print(by_skill.most_common())
